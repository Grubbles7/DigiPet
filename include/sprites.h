// ── Renderer ──────────────────────────────────────────────────────────────────
inline void drawStageSpriteInZone(TFT_eSPI &tft,
                                  uint8_t formId,
                                  int zoneX, int zoneY,
                                  int zoneW, int zoneH,
                                  int yOffset) {
  if (formId >= FORM_COUNT) formId = FORM_DIGIEGG;
  const uint8_t (* grid)[SPR_SIZE] = FORM_SPRITES[formId];

  int drawX = zoneX + (zoneW - SPR_SIZE * SPR_SCALE) / 2;
  int drawY = zoneY + (zoneH - SPR_SIZE * SPR_SCALE) / 2 + yOffset;

  for (int row = 0; row < SPR_SIZE; row++) {
    for (int col = 0; col < SPR_SIZE; col++) {
      uint8_t idx = grid[row][col];
      if (idx == 0) continue;
      if (idx >= SPR_PAL_SIZE) continue;
      tft.fillRect(drawX + col * SPR_SCALE,
                   drawY + row * SPR_SCALE,
                   SPR_SCALE, SPR_SCALE,
                   SPRITE_PALETTE[idx]);
    }
  }
}
